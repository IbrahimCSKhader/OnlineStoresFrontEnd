const translations = new Map(storefrontTextRows.map(([source, english, hebrew]) => [source, { E: english, I: hebrew }]));

export function translateStorefrontText(language, source, ...values) {
  const translated = translations.get(source)?.[language] ?? source;
  return translated.replace(/\{(\d+)\}/g, (placeholder, index) =>
    index < values.length ? String(values[index] ?? "") : placeholder,
  );
}
